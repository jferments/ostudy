export function tokenVariable(name) {
  return `--ostudy-${name.replace(/[A-Z]/gu, (value) => `-${value.toLowerCase()}`).replaceAll(".", "-").replace(/([a-z])(\d)/gu, "$1-$2")}`;
}

export function renderTailwindTheme(availableTokens) {
  const missing = [...new Set(Object.values(themeAliases))].filter((name) => !availableTokens.has(name));
  if (missing.length) throw new Error(`Tailwind bridge references unknown oStudy tokens: ${missing.join(", ")}`);
  return [
    "/* Generated by scripts/generate-ui-tokens.mjs. Do not edit directly. */",
    "@theme inline {",
    ...Object.entries(themeAliases).map(([name, token]) => `  --${name}: var(${tokenVariable(token)});`),
    "  --font-sans: var(--ui-font-family);",
    "  --spacing-touch: var(--touch-target-min);",
    "}",
    "",
  ].join("\n");
}
